'use strict';
var fs = require('node:fs');
var path = require('node:path');

var ROOT = path.join(__dirname, '..');
var PAGE = path.join(ROOT, 'public', 'index.html');
var MODS = [['LabLogic', 'logic.js'], ['LabValidate', 'validate.js'], ['LabFold', 'fold.js']];
var START = '/*INLINE:start (generated by tools/inline.js from shared/*.js: do not edit)*/';
var END = '/*INLINE:end*/';

function block() {
  var parts = MODS.map(function (m) {
    var src = fs.readFileSync(path.join(ROOT, 'shared', m[1]), 'utf8').replace(/^\/\*[\s\S]*?\*\/\n/, '').replace("'use strict';\n", '').trim();
    if (src.indexOf('</script') >= 0) throw new Error(m[1] + ' contains </script');
    return 'var ' + m[0] + '=(function(){var module={exports:{}};\n' + src + '\nreturn module.exports})();';
  });
  return START + '\n' + parts.join('\n') + '\n' + END;
}
function build(html) {
  var a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < 0) throw new Error('INLINE markers not found in public/index.html');
  return html.slice(0, a) + block() + html.slice(b + END.length);
}
if (require.main === module) {
  var cur = fs.readFileSync(PAGE, 'utf8'), next = build(cur);
  if (process.argv.indexOf('--check') >= 0) { if (cur !== next) { console.error('public/index.html is out of date: run node tools/inline.js'); process.exit(1); } }
  else { fs.writeFileSync(PAGE, next); console.log('inlined ' + MODS.length + ' modules'); }
}
module.exports = { build: build, block: block };
